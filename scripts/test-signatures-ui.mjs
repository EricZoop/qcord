import assert from "node:assert/strict";
import {launchBrowser} from "./browser.mjs";
import {serveFixture} from "./ui-server.mjs";

const {server, url} = await serveFixture();
let browser;
try {
    browser = await launchBrowser();
    const page = await browser.newPage({viewport: {width: 1440, height: 1000}}), errors = [];
    page.on("pageerror", error => errors.push(error.message));
    await page.route("https://cdn.discordapp.com/avatars/**", route => route.fulfill({status: 404}));
    await page.goto(url);
    await page.getByRole("dialog", {name: "Qcord encapsulation", exact: true}).waitFor();
    const viewer = page.getByRole("dialog", {name: "Qcord signature verification", exact: true});
    const demo = async failed => {
        const id = await page.evaluate(failed => window.qcordTest.signatureDemo(failed), failed);
        const message = page.locator(`#chat-messages-100-${id} .qcord-decrypted`);
        await message.waitFor();
        return message;
    };
    const verified = await demo(false);
    assert.equal(await verified.getAttribute("data-signature"), "verified");
    assert.equal(await verified.locator("button").count(), 1, "Only the original corner control remains");
    assert.equal(await verified.locator(".qcord-signature").count(), 0);
    const check = verified.getByRole("button", {name: "Check Signature Challenge: signature verified", exact: true});
    assert.equal(await check.locator("path").getAttribute("d"), "M20 6 9 17l-5-5");
    await check.click(); await viewer.waitFor();
    await viewer.getByLabel("Saved public signature key", {exact: true}).waitFor();
    assert.equal(await viewer.getByRole("link", {name: "Download .qcord"}).count(), 1);
    assert.deepEqual(await viewer.locator(".qc-signature-parts > div span").allTextContents(), ["32 bytes", "1920 bytes · 6 polynomials"]);
    await page.screenshot({path: ".tools/ui/17-signature-key.png"});
    await viewer.getByRole("button", {name: "Next", exact: true}).click();
    assert.match(await viewer.locator(".qc-explanation").innerText(), /Az − ct = w − cs₂/);
    assert.match(await viewer.locator(".qc-polynomial figcaption").innerText(), /w′₁\[0\]/);
    await viewer.getByRole("button", {name: "w′₁[5]", exact: true}).click();
    assert.match(await viewer.locator(".qc-polynomial figcaption").innerText(), /w′₁\[5\]/);
    const mathStyle = await viewer.locator('[role="math"]').first().evaluate(el => ({font: getComputedStyle(el).fontFamily, color: getComputedStyle(el).color}));
    assert.match(mathStyle.font, /Cambria/); assert.equal(mathStyle.color, "rgb(241, 243, 245)");
    await page.screenshot({path: ".tools/ui/18-signature-commitment.png"});
    await viewer.getByRole("button", {name: "Next", exact: true}).click();
    const received = viewer.getByLabel("Received challenge c tilde", {exact: true});
    const recomputed = viewer.getByLabel("Recomputed challenge c tilde prime", {exact: true});
    assert.equal(await received.inputValue(), await recomputed.inputValue());
    assert.equal(await viewer.locator(".qc-verification-result").getAttribute("data-status"), "verified");
    assert.match(await viewer.locator(".qc-explanation").innerText(), /H\(M ∥ HighBits\(Az − ct\)\) = c/);
    await page.setViewportSize({width: 1366, height: 768});
    assert.ok(await viewer.evaluate(el => el.scrollHeight <= el.clientHeight + 2));
    await page.screenshot({path: ".tools/ui/19-signature-verified.png"});
    await viewer.getByRole("button", {name: "Done", exact: true}).click(); await viewer.waitFor({state: "detached"});
    const failed = await demo(true);
    assert.equal(await failed.getAttribute("data-signature"), "failed");
    assert.equal(await failed.locator("button").count(), 1);
    assert.equal(await failed.evaluate(el => getComputedStyle(el).borderColor), "rgb(212, 89, 102)");
    await failed.getByRole("button", {name: "Check Signature Challenge: signature failed", exact: true}).click();
    await viewer.waitFor(); await viewer.getByLabel("Saved public signature key", {exact: true}).waitFor();
    await viewer.getByRole("tab", {name: "3. Check challenge", exact: true}).click();
    assert.notEqual(await received.inputValue(), await recomputed.inputValue());
    assert.equal(await viewer.locator(".qc-verification-result").getAttribute("data-status"), "failed");
    await page.screenshot({path: ".tools/ui/20-signature-failed.png"});
    await viewer.getByRole("button", {name: "Done", exact: true}).click(); await viewer.waitFor({state: "detached"});
    // Manual verification works independently of the automatic preference.
    const wire = await page.evaluate(async () => {
        window.qcordTest.plugin.setAutomatic("verify", false);
        const wire = await window.qcordTest.incomingWire("Manually checked signature");
        window.qcordTest.addAttachment(wire, {id: "51000"}); return wire;
    });
    const manual = page.locator("#chat-messages-100-51000 .qcord-decrypted"); await manual.waitFor();
    assert.equal(await manual.getAttribute("data-signature"), "unchecked");
    await manual.getByRole("button", {name: "Check Signature Challenge: signature not checked", exact: true}).click();
    await viewer.getByLabel("Saved public signature key", {exact: true}).waitFor();
    assert.equal(await manual.getAttribute("data-signature"), "unchecked", "Manual walkthrough updates the corner icon at the final check");
    await viewer.getByRole("tab", {name: "3. Check challenge", exact: true}).click();
    await manual.getByRole("button", {name: "Check Signature Challenge: signature verified", exact: true}).waitFor();
    assert.equal(await manual.getAttribute("data-signature"), "verified");
    await viewer.getByRole("button", {name: "Go Back", exact: true}).click(); await viewer.waitFor({state: "detached"});
    await page.evaluate(wire => {
        window.qcordTest.data.recipients.find(row => row.channel_id === "100").public_signature = "";
        window.qcordTest.plugin.setAutomatic("verify", true);
        window.qcordTest.addAttachment(wire, {id: "51001"});
    }, wire);
    const missing = page.locator("#chat-messages-100-51001 .qcord-decrypted"); await missing.waitFor();
    assert.equal(await missing.getAttribute("data-signature"), "missing-key");
    await missing.getByRole("button", {name: "Check Signature Challenge: sender key missing", exact: true}).click();
    await viewer.waitFor();
    await viewer.getByText("Save the sender's public signature key in the recipient panel before verifying.", {exact: true}).first().waitFor();
    assert.equal(await viewer.getByRole("button", {name: "Next", exact: true}).isDisabled(), true);
    await page.evaluate(() => window.qcordTest.plugin.stop());
    await viewer.waitFor({state: "detached"});
    assert.deepEqual(errors, []);
    console.log("Signature browser checks passed: real signed demos, single corner control, lecture equations, reconstructed challenge match/mismatch, auto/manual verification, missing key, red failure bubble and teardown.");
} finally { await browser?.close(); await new Promise(resolve => server.close(resolve)); }
