import {build} from "esbuild";
import {chromium} from "playwright";
import {mkdir, writeFile} from "node:fs/promises";
import {createServer} from "node:http";
import {readFileSync} from "node:fs";
import assert from "node:assert/strict";
await mkdir(".tools/ui", {recursive: true});
await build({entryPoints: ["scripts/ui-fixture.js"], outfile: ".tools/ui/panel.js", bundle: true, platform: "browser", format: "esm", loader: {".css": "text", ".svg": "text"}});
await writeFile(".tools/ui/index.html", '<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width"><title>Qcord test</title><style>body{margin:0;background:#18191c;color-scheme:dark}button,input,select{font-family:system-ui}</style><script type="module" src="/panel.js"></script></html>');
const server = createServer((req, res) => { res.setHeader("Content-Type", req.url === "/panel.js" ? "text/javascript" : "text/html"); res.end(readFileSync(req.url === "/panel.js" ? ".tools/ui/panel.js" : ".tools/ui/index.html")); });
await new Promise(r => server.listen(0, "127.0.0.1", r));
let browser;
try {
    browser = await chromium.launch({headless: true, ...(process.env.QCORD_BROWSER ? {executablePath: process.env.QCORD_BROWSER} : {})});
    const page = await browser.newPage({viewport: {width: 1600, height: 1000}}), errors = [];
    page.on("pageerror", e => errors.push(e.message));
    await page.route("https://cdn.discordapp.com/avatars/**", route => route.fulfill({contentType: "image/svg+xml", body: '<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64"><rect width="64" height="64" fill="#587451"/></svg>'}));
    await page.goto(`http://127.0.0.1:${server.address().port}`);
    const composer = page.getByRole("dialog", {name: "Qcord encapsulation", exact: true});
    await composer.waitFor();
    const idle = () => page.waitForFunction(() => !document.querySelector('.qc-main[aria-busy="true"]'));
    const stage = async name => { await composer.getByRole("tab", {name, exact: true}).click(); await idle(); };
    const noOuterOverflow = async () => {
        const overflow = await composer.evaluate(el => ({dialog: el.scrollHeight - el.clientHeight, panel: el.firstElementChild.scrollHeight - el.firstElementChild.clientHeight}));
        assert.ok(overflow.dialog <= 2 && overflow.panel <= 2, JSON.stringify(overflow));
    };
    assert.equal(await composer.getByRole("tab", {name: "1. Recipient key", exact: true}).getAttribute("aria-selected"), "true");
    assert.equal(await composer.locator("textarea:not([readonly])").count(), 0, "No chat-text entry step");
    await composer.getByRole("tab", {name: "Saved public_encaps", exact: true}).click();
    assert.ok((await composer.getByLabel("Saved public_encaps").inputValue()).length > 1000);
    await composer.getByRole("tab", {name: "Dimensions", exact: true}).click();
    await noOuterOverflow(); await page.screenshot({path: ".tools/ui/01-recipient-key.png"});

    // Paste a different set's key and verify automatic parameter detection through the actual contacts UI.
    const public512 = await page.evaluate(() => window.qcordTest.plugin.getRecipients("100", "ml-kem-512")[0].public_encaps);
    await composer.getByRole("button", {name: "Contacts & keys", exact: true}).click();
    const contacts = page.getByRole("dialog", {name: "Contacts and keys", exact: true});
    await contacts.getByRole("textbox", {name: "ML-KEM-768 public key", exact: true}).fill(public512);
    await contacts.getByRole("button", {name: "Replace public key", exact: true}).click();
    await page.waitForFunction(() => window.qcordTest.plugin.scheme === "ml-kem-512");
    await contacts.getByRole("button", {name: "Use this recipient", exact: true}).click();
    await contacts.waitFor({state: "detached"});
    assert.equal(await composer.getByLabel("ML-KEM parameter set").inputValue(), "ml-kem-512");

    for (const [scheme, k, category] of [["ml-kem-512", 2, 1], ["ml-kem-768", 3, 3], ["ml-kem-1024", 4, 5]]) {
        await composer.getByLabel("ML-KEM parameter set").selectOption(scheme);
        assert.equal(await composer.locator(".qc-level strong").innerText(), String(category));
        assert.equal(await composer.getByLabel("Matrix dimensions").locator("span").count(), k * k);
        assert.equal(await composer.getByLabel("Vector dimensions").locator("span").count(), k);
        await composer.getByRole("tab", {name: "Matrix Â", exact: true}).click();
        assert.equal(await composer.getByLabel("Public matrix A hat").getByRole("button").count(), k * k);
        await composer.getByRole("tab", {name: "Dimensions", exact: true}).click();
        await stage("2. Derive K");
        const oldM = await composer.locator(".qc-code").first().innerText();
        await composer.getByRole("button", {name: "Sample fresh m", exact: true}).click(); await idle();
        assert.notEqual(await composer.locator(".qc-code").first().innerText(), oldM);
        await noOuterOverflow();
        if (k === 3) await page.screenshot({path: ".tools/ui/02-derive-k.png"});
        await stage("3. Construct u, v");
        await composer.getByRole("tab", {name: "Compute u", exact: true}).click();
        await composer.getByLabel("Vector index").selectOption(String(k - 1));
        await composer.getByLabel("Construction coefficient").fill("17");
        assert.match(await composer.locator(".qc-visual .qc-code").innerText(), new RegExp(`u\\[${k - 1}\\]\\[17\\]`));
        await composer.getByRole("tab", {name: "Compute v", exact: true}).click();
        assert.match(await composer.locator(".qc-visual .qc-code").innerText(), /v\[17\]/);
        if (k === 3) await page.screenshot({path: ".tools/ui/03-construct-v.png"});
        await stage("4. Attach");
        const wire = await composer.locator(".qc-json").innerText(), file = JSON.parse(wire);
        assert.equal(file.parameter_set, scheme); assert.equal(file.u.length, k);
        assert.deepEqual(Object.keys(file).sort(), ["parameter_set", "qcord_version", "u", "v"]);
        await noOuterOverflow();
        await composer.getByRole("button", {name: "Attach .qcord to composer", exact: true}).click(); await idle();
        assert.equal(await page.evaluate(async () => window.qcordTest.state.staged.at(-1).files[0].file.text()), wire);
        const savedCount = await page.evaluate(s => window.qcordTest.plugin.getRecipients("100", s)[0].encapsulations.length, scheme);
        assert.equal(savedCount, 1);
        await composer.getByLabel("Open .qcord locally").setInputFiles({name: "saved.qcord", mimeType: "application/json", buffer: Buffer.from(wire)});
        await idle();
        await composer.getByRole("status").filter({hasText: "Saved sender m"}).waitFor();
        if (k === 3) await page.screenshot({path: ".tools/ui/04-attachment.png"});
        await stage("1. Recipient key");
        await composer.getByRole("tab", {name: "Dimensions", exact: true}).click();
    }
    await page.evaluate(() => window.qcordTest.actions.sendMessage("100", {content: "Ordinary Discord text"}));
    assert.equal(await page.evaluate(() => window.qcordTest.state.sent.length), 1);
    assert.equal(await page.evaluate(() => window.qcordTest.state.staged.length), 3);
    await page.setViewportSize({width: 1366, height: 768}); await noOuterOverflow();
    await page.screenshot({path: ".tools/ui/05-laptop.png"});
    await page.setViewportSize({width: 390, height: 844});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({path: ".tools/ui/06-narrow.png"});
    await page.evaluate(() => window.qcordTest.plugin.stop()); await composer.waitFor({state: "detached"});
    assert.deepEqual(errors, []);
    console.log("Browser checks passed: key-first flow, automatic set detection, dimensions, derivation, real u/v, all three sets, exact staging, saved m, ordinary Discord sending, responsive layout, teardown.");
} finally { await browser?.close(); await new Promise(r => server.close(r)); }
